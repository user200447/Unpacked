// Test fixtures shared by the core modules' commonTest source sets: the synthetic Instagram
// Export generator and the hand-written record constants. Never a dependency of main code.
plugins {
    id("unpacked.kmp.library")
}

kotlin {
    sourceSets {
        commonMain.dependencies {
            api(project(":core:model"))
            api(libs.okio)
            // The Sample Export lists its files by writing the generator's output to an in-memory file system.
            implementation(libs.okio.fakefilesystem)
        }
    }
}

// The Sample Export (README): the generator's full synthetic Export, zipped into the repository by this task
// and regenerated by it on demand. The test over the zip in core:data proves it is what the generator writes.
tasks.register<JavaExec>("writeSampleExport") {
    description = "Writes the synthetic Sample Export to sample/instagram-sample-export.zip."
    group = "build"
    val jvmMain = kotlin.jvm().compilations.getByName("main")
    val zip = rootProject.layout.projectDirectory.file("sample/instagram-sample-export.zip")
    classpath = files(jvmMain.output.allOutputs, configurations.getByName(jvmMain.runtimeDependencyConfigurationName))
    mainClass.set("com.jassemsendi.unpacked.fixtures.SampleExportZip")
    args(zip.asFile.absolutePath)
    outputs.file(zip)
}
