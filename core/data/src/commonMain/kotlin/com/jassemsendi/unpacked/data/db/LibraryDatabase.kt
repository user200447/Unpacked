package com.jassemsendi.unpacked.data.db

import androidx.room.ConstructedBy
import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor

/**
 * The local library's schema (ADR 0004). The exported schema lives in `core/data/schemas`; version 2
 * added the item index to the Provenance columns, version 3 the full-text search tables.
 */
@Database(
    entities = [
        ImportRow::class,
        ImportFileRow::class,
        EventRow::class,
        EventAttributeRow::class,
        EventEntityRow::class,
        ClaimRow::class,
        ClaimAttributeRow::class,
        ClaimEntityRow::class,
        EntityRow::class,
        EntityAttributeRow::class,
        EventTextRow::class,
        ClaimTextRow::class,
        EventSearchRow::class,
        ClaimSearchRow::class,
    ],
    version = 3,
    exportSchema = true,
)
@ConstructedBy(LibraryDatabaseConstructor::class)
internal abstract class LibraryDatabase : RoomDatabase() {
    abstract fun importDao(): ImportDao

    abstract fun eventDao(): EventDao

    abstract fun claimDao(): ClaimDao

    abstract fun entityDao(): EntityDao

    abstract fun searchDao(): SearchDao

    abstract fun entityCountDao(): EntityCountDao
}

/** The actual object is generated by Room's KSP processor for every target. */
@Suppress("KOTLIN_NO_ACTUAL_FOR_EXPECT", "EXPECT_ACTUAL_CLASSIFIERS_ARE_IN_BETA_WARNING")
internal expect object LibraryDatabaseConstructor : RoomDatabaseConstructor<LibraryDatabase> {
    override fun initialize(): LibraryDatabase
}
